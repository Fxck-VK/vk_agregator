import { existsSync, mkdirSync, readFileSync, readdirSync, watch, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const platformDirectory = fileURLToPath(new URL("..", import.meta.url));

/** Only source generation uses fs. The deployed server uses static imports. */
export function generatePublicPageManifest(root = platformDirectory) {
  const publicRoot = resolve(root, "src/app/(public)");
  const output = resolve(root, "src/content/publication/generated.ts");
  const sources = [];
  function visit(directory, segments) {
    const entries = readdirSync(directory, { withFileTypes: true });
    const page = entries.find(entry => entry.isFile() && /^page\.[jt]sx?$/.test(entry.name));
    const declaration = entries.some(entry => entry.isFile() && entry.name === "publication.ts");
    if (page && !declaration) throw new Error(`Public page ${relative(publicRoot, directory) || "/"} requires publication.ts (use an empty collection for noindex routes).`);
    if (declaration && !page) throw new Error(`Publication ${relative(publicRoot, directory)} requires an implemented page.tsx.`);
    if (declaration) sources.push({ route: `/${segments.join("/")}`, path: resolve(directory, "publication") });
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, "en"))) {
      if (!entry.isDirectory() || entry.name.startsWith("_") || entry.name.startsWith("@")) continue;
      const group = /^\([a-zA-Z0-9_-]+\)$/.test(entry.name);
      visit(resolve(directory, entry.name), group ? segments : [...segments, entry.name]);
    }
  }
  visit(publicRoot, []);
  if (new Set(sources.map(source => source.route)).size !== sources.length) throw new Error("Duplicate implemented public route.");
  const imports = sources.map((source, index) => {
    const path = relative(dirname(output), source.path).split(sep).join("/");
    return `import { publications as pages${index} } from ${JSON.stringify(path.startsWith(".") ? path : `./${path}`)};`;
  });
  const code = [
    "// Generated by scripts/public-page-manifest.mjs. Do not edit or commit.",
    'import "server-only";',
    'import type { PublicPageSource } from "./types";',
    ...imports,
    "", "export const publicPageSources = [",
    ...sources.map((source, index) => `  { route: ${JSON.stringify(source.route)}, pages: pages${index} },`),
    "] satisfies readonly PublicPageSource[];", "",
  ].join("\n");
  if (!existsSync(output) || readFileSync(output, "utf8") !== code) {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, code);
  }
  return sources.length;
}

export function watchPublicPages(root = platformDirectory) {
  let pending;
  const watcher = watch(resolve(root, "src/app/(public)"), { recursive: true }, (_event, filename) => {
    if (filename && !/(?:publication\.ts|page\.[jt]sx?)$/.test(String(filename))) return;
    clearTimeout(pending);
    pending = setTimeout(() => {
      try { generatePublicPageManifest(root); }
      catch (error) { console.error(`Public page discovery: ${error.message}`); }
    }, 100);
  });
  return () => { clearTimeout(pending); watcher.close(); };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(`Public page publication sources: ${generatePublicPageManifest(process.argv[2])}`); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
