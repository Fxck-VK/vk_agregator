import {existsSync,mkdirSync,readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {sourceLoader} from './content-source-loader.mjs';
import {requirePublicMediaFile,requireTemplateMediaFile} from './content-assets.mjs';

const root=fileURLToPath(new URL('..',import.meta.url));
const load=sourceLoader(root);
const {templateDefaults}=load(resolve(root,'src/content/templates/defaults.ts'));
const {templateDefinitions}=load(resolve(root,'src/content/templates/registry.ts'));
const {validateContentPages}=load(resolve(root,'src/content/templates/validation.ts'));
const {localizePublicData}=load(resolve(root,'src/i18n/public/public-copy.ts'));
const base=JSON.parse(readFileSync(resolve(root,'src/content/pages/catalog.json'),'utf8'));
const entries=resolve(root,'src/content/pages/entries');mkdirSync(entries,{recursive:true});
const action=process.argv[2]??'check';

if(action==='list')console.log(templateDefinitions.map(t=>`${t.id}\t${t.label}\t${t.path}${t.managed?'\tmanaged':''}`).join('\n'));
else if(action==='examples'){
  const outputDirectory=resolve(root,'docs/content-examples');mkdirSync(outputDirectory,{recursive:true});
  for(const definition of templateDefinitions){
    const page=structuredClone(base.find(p=>p.template===definition.id));
    page.status='draft';page.indexing='noindex';delete page.publishedAt;delete page.updatedAt;delete page.reviewedAt;
    page.content=definition.managed?{}:JSON.parse(JSON.stringify(localizePublicData(templateDefaults[definition.id],'ru')));
    writeFileSync(resolve(outputDirectory,definition.id+'.json'),JSON.stringify(page,null,2)+'\n');
  }
  console.log('Примеры 24 типов: '+outputDirectory);
}
else if(action==='new'){
  const [template,slug]=process.argv.slice(3);
  const definition=templateDefinitions.find(t=>t.id===template);
  if(!definition||!slug||!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug))throw new Error('Usage: npm run content:new -- T09 my-article');
  if(['T01','T18','T23'].includes(template))throw new Error('Редактируйте существующую каноническую запись этого типа.');
  const sample=base.find(p=>p.template===template),page=structuredClone(sample);
  page.id=slug;page.path=sample.path.slice(0,sample.path.lastIndexOf('/')+1)+slug;
  if(template==='T17')page.path='/integrations/'+slug;
  if(template==='T19')page.path='/business/'+slug;
  if(template==='T11')page.path='/help/'+slug;
  page.status='draft';page.indexing='noindex';page.relatedIds=[];
  delete page.publishedAt;delete page.updatedAt;delete page.reviewedAt;
  page.content=JSON.parse(JSON.stringify(localizePublicData(templateDefaults[template],'ru')));
  if(template==='T15')page.content.initialMaterialFilters.query='';
  // Identities used by share/bookmark controls must belong to the new public record.
  for(const value of Object.values(page.content))if(value&&typeof value==='object'&&!Array.isArray(value)){
    if('slug'in value)value.slug=slug;
    if('path'in value)value.path=page.path;
    if('id'in value)value.id=page.id;
  }
  const file=resolve(entries,slug+'.json');
  if(existsSync(file))throw new Error('Такая запись уже существует.');
  const existing=readdirSync(entries).filter(f=>f.endsWith('.json')).map(f=>JSON.parse(readFileSync(resolve(entries,f),'utf8')));
  validateContentPages([...base,...existing,page],templateDefaults);
  writeFileSync(file,JSON.stringify(page,null,2)+'\n');
  console.log(`Создан черновик: ${file}\nПредпросмотр: http://localhost:7159/ru${page.path}`);
}else if(action!=='check')throw new Error('Supported commands: check, list, new, examples.');

const files=readdirSync(entries).filter(f=>f.endsWith('.json')).sort();
const pages=validateContentPages([...base,...files.map(file=>JSON.parse(readFileSync(resolve(entries,file),'utf8')))],templateDefaults);
const generated=['// Generated by scripts/content-pages.mjs. Do not edit.',...files.map((f,i)=>`import entry${i} from ${JSON.stringify('./entries/'+f)};`),`export const additionalContentPages = [${files.map((_,i)=>'entry'+i).join(',')}];`,''].join('\n');
const output=resolve(root,'src/content/pages/generated.ts');
if(!existsSync(output)||readFileSync(output,'utf8')!==generated)writeFileSync(output,generated);

// Validate the expanded catalogue too: otherwise a lesson could shadow a real page.
const {expandContentPages}=load(resolve(root,'src/content/templates/catalog.ts'));
const expanded=expandContentPages(pages),paths=new Set(),ids=new Set();
for(const page of expanded){
  if(paths.has(page.path)||ids.has(page.id))throw new Error('Duplicate expanded page/lesson/help URL or ID: '+page.path);
  paths.add(page.path);ids.add(page.id);
}
// A catalogue record cannot take over a fixed auth/workspace or unrelated public route.
const staticPages=[];
function walk(directory,segments=[]){for(const e of readdirSync(directory,{withFileTypes:true})){
  if(e.isDirectory()&&!e.name.startsWith('_')&&!e.name.startsWith('@'))walk(resolve(directory,e.name),/^\(.+\)$/.test(e.name)?segments:[...segments,e.name]);
  else if(e.isFile()&&e.name==='page.tsx')staticPages.push('/'+segments.join('/'));
}}
walk(resolve(root,'src/app'));
for(const page of expanded){const definition=templateDefinitions.find(t=>t.id===page.template);
  if(page.path!==definition.path&&staticPages.includes(page.path))throw new Error('Content collides with an implemented static route: '+page.path);
}
const assetRoot=resolve(root,'public');
const assets=[];
function assetFiles(directory){for(const e of readdirSync(directory,{withFileTypes:true})){const file=resolve(directory,e.name);if(e.isDirectory())assetFiles(file);else assets.push(file.replaceAll('\\','/'));}}
assetFiles(resolve(assetRoot,'assets'));
function media(value,key='',prototype){
  if(Array.isArray(value)){value.forEach((v,i)=>media(v,'',prototype?.[i]??prototype?.[0]));return;}
  if(value&&typeof value==='object'){for(const[k,v]of Object.entries(value))media(v,k,prototype?.[k]);return;}
  if(typeof value==='string'&&['src','poster','avatar'].includes(key)&&value.startsWith('/assets/')){
    requirePublicMediaFile(assetRoot,value);
  }
  if((key==='file'||key==='poster'&&!String(value).startsWith('/assets/'))&&typeof value==='string'&&typeof prototype==='string'){
    requireTemplateMediaFile(assets,value,prototype);
  }
}
for(const page of pages)media(page.content,'',templateDefaults[page.template]);
if(action==='examples'){
  const examples=templateDefinitions.map(t=>JSON.parse(readFileSync(resolve(root,'docs/content-examples',t.id+'.json'),'utf8')));
  validateContentPages(examples,templateDefaults);
  for(const page of examples)media(page.content,'',templateDefaults[page.template]);
}
if(action!=='list')console.log(`Каталог: ${pages.length} записей, ${expanded.length} страниц, ${templateDefinitions.length} шаблона. Проверка пройдена.`);
