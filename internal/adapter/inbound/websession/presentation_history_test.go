func TestPresentationHistoryRequiresDevAndAccount(t *testing.T) {
	h, _, sessions, _, _ := newWebConversationMessageTestHandler(t)
	h.cfg.Environment = "development"
	for _, test := range []struct {
		name  string
		view  string
		owner uuid.UUID
		want  int
	}{
		{"unauthenticated", "dev", uuid.Nil, http.StatusUnauthorized},
		{"production view", "prod", uuid.New(), http.StatusNotFound},
		{"authenticated DEV route", "dev", uuid.New(), http.StatusServiceUnavailable},
	} {
		t.Run(test.name, func(t *testing.T) {
			req := httptest.NewRequest(http.MethodGet, "/web/v1/presentations", nil)
			if test.owner != uuid.Nil {
				req = authenticatedConversationRequest(t, http.MethodGet, "/web/v1/presentations", sessions, test.owner)
			}
			req.Header.Set("X-Epifera-Release-View", test.view)
			response := httptest.NewRecorder()
			h.Routes().ServeHTTP(response, req)
			if response.Code != test.want {
				t.Fatalf("status %d, want %d", response.Code, test.want)
			}
		})
	}
}

func TestPresentationHistoryPaginatesOwnerAndDerivesLegacyTitle(t *testing.T) {
	h, _, sessions, _, _ := newWebConversationMessageTestHandler(t)
	h.cfg.Environment = "development"
	owner, foreignOwner := uuid.New(), uuid.New()
	createdAt := time.Date(2026, 11, 25, 13, 39, 10, 0, time.UTC)
	legacy := domain.PresentationHistoryRow{
		AccountID: owner, ConversationID: uuid.New(), JobID: uuid.New(),
		Title: "## A generated slide", TitleOrigin: domain.ConversationTitleOriginAutoGenerated,
		TitlePrompt: "Подготовь презентацию на русском языке. Тема: Alfa Romeo.\n\nBrief details only",
		Status:      domain.JobStatusFailedTerminal, CreatedAt: createdAt, ModelName: "Qwen 3.7 Flash", ErrorCode: string(domain.ProviderErrTimeout),
	}
	older := domain.PresentationHistoryRow{
		AccountID: owner, ConversationID: uuid.New(), JobID: uuid.New(),
		Title: "Моя презентация", TitleOrigin: domain.ConversationTitleOriginManual,
		Status: domain.JobStatusSucceeded, CreatedAt: createdAt.Add(-time.Minute),
	}
	reads := 0
	h.deps.PresentationHistory = presentationHistoryReaderFunc(func(_ context.Context, accountID uuid.UUID, limit int, after *domain.JobCursor) ([]domain.PresentationHistoryRow, error) {
		reads++
		if accountID != owner {
			return nil, nil
		}
		if limit != 2 {
			t.Fatalf("requested row limit %d, want page size + one", limit)
		}
		if after == nil {
			return []domain.PresentationHistoryRow{legacy, older}, nil
		}
		if after.ID != legacy.JobID || !after.CreatedAt.Equal(legacy.CreatedAt) {
			t.Fatalf("pagination starts after %#v, want original last item", after)
		}
		return []domain.PresentationHistoryRow{older}, nil
	})
	get := func(account uuid.UUID, query string) *httptest.ResponseRecorder {
		t.Helper()
		req := authenticatedConversationRequest(t, http.MethodGet, "/web/v1/presentations?"+query, sessions, account)
		req.Header.Set("X-Epifera-Release-View", "dev")
		response := httptest.NewRecorder()
		h.Routes().ServeHTTP(response, req)
		return response
	}
	first := get(owner, "limit=1")
	var page presentationHistoryPage
	if first.Code != http.StatusOK || json.Unmarshal(first.Body.Bytes(), &page) != nil || len(page.Items) != 1 || page.NextCursor == "" {
		t.Fatalf("unexpected first page %d %s", first.Code, first.Body)
	}
	got := page.Items[0]
	if got.JobID != legacy.JobID || got.ConversationID != legacy.ConversationID || got.Title != "Презентация · Alfa Romeo" || got.FailureCode != "provider_unavailable" || got.ModelName != legacy.ModelName || first.Header().Get("Cache-Control") != "no-store" {
		t.Fatalf("unexpected history item: %#v", got)
	}
	if strings.Contains(first.Body.String(), "Brief details only") || strings.Contains(first.Body.String(), "A generated slide") || strings.Contains(first.Body.String(), "provider_timeout") {
		t.Fatal("private job details or legacy generated heading escaped metadata projection")
	}
	secondQuery := "limit=1&cursor=" + page.NextCursor
	second := get(owner, secondQuery)
	page = presentationHistoryPage{}
	if second.Code != http.StatusOK || json.Unmarshal(second.Body.Bytes(), &page) != nil || len(page.Items) != 1 || page.Items[0].JobID != older.JobID || page.Items[0].Title != older.Title || page.NextCursor != "" {
		t.Fatalf("unexpected second page %d %s", second.Code, second.Body)
	}
	for _, query := range []string{secondQuery, "limit=51", "limit=1&limit=2", "cursor=broken"} {
		if response := get(foreignOwner, query); response.Code != http.StatusBadRequest || reads != 2 {
			t.Fatalf("invalid query / foreign cursor: status %d, total reads %d", response.Code, reads)
		}
	}
	foreign := get(foreignOwner, "limit=1")
	if foreign.Code != http.StatusOK || !strings.Contains(foreign.Body.String(), `"items":[]`) {
		t.Fatalf("foreign history empty oracle returned %d %s", foreign.Code, foreign.Body)
	}
}

type presentationHistoryReaderFunc func(context.Context, uuid.UUID, int, *domain.JobCursor) ([]domain.PresentationHistoryRow, error)

func (read presentationHistoryReaderFunc) ListPresentationHistory(ctx context.Context, owner uuid.UUID, limit int, after *domain.JobCursor) ([]domain.PresentationHistoryRow, error) {
	return read(ctx, owner, limit, after)
}
